// Task 1.4: Use a switch statement to print the day name for numbers 1–7. Print "Invalid" for any other value.
let dayNumber = 5
switch dayNumber {
case 1: print("Sunday")
case 2: print("Monday")
case 3: print("Tuesday")
case 4: print("Wednesday")
case 5: print("Thursday")
case 6: print("Friday")
case 7: print("Saturday")
default: print("Invalid")
}
